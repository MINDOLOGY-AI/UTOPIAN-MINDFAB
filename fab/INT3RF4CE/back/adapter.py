class Adapter(ABC):
    """Base class for model-specific format adapters."""

    @abstractmethod
    def api_tools(self, allowed: set | None = None) -> list[dict]:
        """Return provider-native tool schemas. `allowed` filters command names (None = all)."""
        raise NotImplementedError

    @abstractmethod
    def to_api_payload(self, model: str, system_prompt: str | None, messages: list[dict],
                       use_tools: bool = True, allowed_tools: set | None = None) -> dict:
        """Build provider-native request payload from internal messages."""
        raise NotImplementedError

    @abstractmethod
    def parse_api_response(self, data: dict) -> list[dict]:
        """Parse provider response JSON into internal content blocks."""
        raise NotImplementedError

    def reasoning_params(self, model: str) -> dict:
        """Extra provider-native parameters for reasoning models. Override if needed."""
        return {}


class OpenAICompatAdapter(Adapter):
    """OpenAI-compatible chat-completions adapter — the shared wire format for
    Kimi (Moonshot), GLM (OpenRouter) and DeepSeek. Provider subclasses only
    override reasoning_params.

    Native format uses role-based messages and tool_calls/tool roles.
    """

    def api_tools(self, allowed: set | None = None) -> list[dict]:
        cmds = COMMANDS if allowed is None else [c for c in COMMANDS if c["name"] in allowed]
        return [{"type": "function", "function": dict(cmd)} for cmd in cmds]

    def reasoning_params(self, model: str) -> dict:
        # moonshot kimi: k3 uses reasoning_effort; k2.7 uses reasoning object.
        if "k3" in model:
            return {"reasoning_effort": "max"}
        return {"reasoning": {"type": "enabled", "keep": "all"}}

    def to_api_payload(self, model: str, system_prompt: str | None, messages: list[dict],
                       use_tools: bool = True, allowed_tools: set | None = None) -> dict:
        payload: dict[str, Any] = {
            "model": model,
            "messages": [],
            "max_tokens": 8192,
        }
        if system_prompt:
            payload["messages"].append({"role": "system", "content": system_prompt})
        payload["messages"].extend(self._to_api_messages(messages))
        payload.update(self.reasoning_params(model))
        if use_tools:
            payload["tools"] = self.api_tools(allowed_tools)
        return payload

    def _to_api_messages(self, messages: list[dict]) -> list[dict]:
        out: list[dict] = []
        i = 0
        while i < len(messages):
            msg = messages[i]
            role = msg.get("role")
            blocks = msg.get("content", [])
            if not isinstance(blocks, list):
                blocks = [{"type": "text", "text": str(blocks)}]

            if role == "system":
                text = self._extract_text(blocks)
                if text:
                    out.append({"role": "system", "content": text})
                i += 1

            elif role == "user":
                # group consecutive user messages: the API requires ALL tool messages
                # to immediately follow the assistant's tool_calls, so every tool
                # result is emitted first, then one user message with text/images
                text_parts: list[str] = []
                image_parts: list[dict] = []
                tool_msgs: list[dict] = []
                while i < len(messages) and messages[i].get("role") == "user":
                    u_blocks = messages[i].get("content", [])
                    if not isinstance(u_blocks, list):
                        u_blocks = [{"type": "text", "text": str(u_blocks)}]
                    texts, images, tool_results = self._split_user_blocks(u_blocks)
                    text_parts.extend(texts)
                    image_parts.extend(images)
                    for tr in tool_results:
                        tool_msg, tr_images = self._tool_result_to_api(tr)
                        tool_msgs.append(tool_msg)
                        image_parts.extend(tr_images)
                    i += 1
                out.extend(tool_msgs)
                if text_parts or image_parts:
                    out.append({"role": "user", "content": self._user_content(text_parts, image_parts)})

            elif role == "assistant":
                text_parts = []
                tool_calls = []
                for b in blocks:
                    t = b.get("type")
                    if t == "text":
                        text_parts.append(b.get("text", ""))
                    elif t == "tool_use":
                        tool_calls.append({
                            "id": b["id"],
                            "type": "function",
                            "function": {
                                "name": b["name"],
                                "arguments": json.dumps(b.get("arguments", {}), ensure_ascii=False),
                            },
                        })
                api_msg: dict[str, Any] = {"role": "assistant"}
                if text_parts:
                    api_msg["content"] = "\n".join(text_parts)
                if tool_calls:
                    api_msg["tool_calls"] = tool_calls
                out.append(api_msg)
                i += 1

            else:
                i += 1

        return out

    def _user_content(self, text_parts: list[str], image_parts: list[dict]):
        # text-only -> plain string; with images -> LIST of text + image_url parts
        # (the API rejects a bare dict content even for a single part)
        content: Any = "\n".join(text_parts)
        if image_parts:
            content = [{"type": "text", "text": content}] if text_parts else []
            content.extend(image_parts)
        return content

    def _split_user_blocks(self, blocks: list[dict]) -> tuple[list[str], list[dict], list[dict]]:
        text_parts: list[str] = []
        image_parts: list[dict] = []
        tool_results: list[dict] = []
        for b in blocks:
            t = b.get("type")
            if t == "text":
                text_parts.append(b.get("text", ""))
            elif t == "image":
                src = b.get("source", {})
                image_parts.append({
                    "type": "image_url",
                    "image_url": {
                        "url": f"data:{src.get('media_type', 'image/png')};base64,{src.get('data', '')}",
                    },
                })
            elif t == "tool_result":
                tool_results.append(b)
        return text_parts, image_parts, tool_results

    def _tool_result_to_api(self, block: dict) -> tuple[dict, list[dict]]:
        """Convert a tool_result block to an API tool message plus any image parts.

        OpenAI-compatible tool roles only accept string content, so image
        sub-blocks are returned separately; the caller attaches them to a user
        message emitted after the full tool-message run.
        """
        content = block.get("content", "")
        text_content = ""
        image_parts: list[dict] = []

        if isinstance(content, list):
            for sub in content:
                if sub.get("type") == "text":
                    text_content += (sub.get("text", "") + "\n")
                elif sub.get("type") == "image":
                    src = sub.get("source", {})
                    image_parts.append({
                        "type": "image_url",
                        "image_url": {
                            "url": f"data:{src.get('media_type', 'image/png')};base64,{src.get('data', '')}",
                        },
                    })
            text_content = text_content.strip()
        elif isinstance(content, str):
            text_content = content

        tool_msg = {
            "role": "tool",
            "tool_call_id": block.get("tool_use_id", ""),
            "name": block.get("name", ""),
            "content": text_content or "[image result]",
        }
        return tool_msg, image_parts

    def _extract_text(self, blocks: list[dict]) -> str:
        return "\n".join(b.get("text", "") for b in blocks if b.get("type") == "text")

    def parse_api_response(self, data: dict) -> list[dict]:
        msg = data["choices"][0]["message"]
        blocks: list[dict] = []

        reasoning = msg.get("reasoning_content")
        if reasoning:
            blocks.append({"type": "text", "text": f"[reasoning]\n{reasoning}"})

        content = msg.get("content")
        if content:
            blocks.append({"type": "text", "text": content})

        for tc in msg.get("tool_calls") or []:
            blocks.append({
                "type": "tool_use",
                "id": tc["id"],
                "tool": "computer_use",
                "name": tc["function"]["name"],
                "arguments": json.loads(tc["function"].get("arguments", "{}")),
            })

        return blocks
