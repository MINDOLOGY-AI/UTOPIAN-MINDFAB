"""Provider adapters: convert between INT3RF4CE's internal standard and each model's native format.

Internal standard (model-agnostic)
==================================
A conversation is a list of messages. Each message has:
  role: "system" | "user" | "assistant"
  content: list[Block]

Blocks:
  {"type": "text", "text": str}
  {"type": "tool_use", "id": str, "tool": str, "name": str, "arguments": dict}
  {"type": "tool_result", "tool_use_id": str, "name": str, "content": str | list[Block]}
  {"type": "image", "source": {"type": "base64", "media_type": str, "data": str}}

- tool_use blocks only appear in assistant messages.
- tool_result blocks only appear in user messages.
- image blocks only appear in user messages.
- tool_call ids are generated by our program, not the model.

Adapters are responsible for:
  1. converting the shared command definitions into provider-native tool schemas.
  2. converting internal messages to provider-native messages.
  3. parsing provider responses back into internal content blocks.

The rest of the app (context, agent, UI) only speaks the internal standard.
"""

import json
from abc import ABC, abstractmethod
from typing import Any


